const fs = require('fs');
const { TITLE, upsertComment, escapeMarkdown } = require('./comment-helper');

module.exports = async ({ github, context, core }) => {
  const prNumber = parseInt(process.env.PR_NUMBER, 10);
  const changelogDir = process.env.CHANGELOG_DIR;
  const stagingDir = process.env.STAGING_DIR || '/tmp/changelog-staging';
  const isFork = process.env.IS_FORK === 'true';
  const commitFailed = process.env.COMMIT_FAILED === 'true';

  const files = fs.readdirSync(stagingDir).filter(f => f.endsWith('.yaml'));
  const content = files.length > 0
    ? fs.readFileSync(`${stagingDir}/${files[0]}`, 'utf8').trim()
    : '';

  const bodyParts = [TITLE, ''];
  if (content) {
    let guidance;
    if (commitFailed) {
      guidance = 'The workflow could not commit this generated changelog change to the PR branch, so the merge-time S3 upload will not include it. Resolve the commit failure or add the generated entry to the PR branch before merging.';
    } else if (isFork) {
      guidance = 'This comment is informational — editing it does not change what gets uploaded. On merge, the entry is regenerated from the live PR record (title, labels) and uploaded to S3. To change the preview, edit the PR title or labels and let the changelog workflow re-run.';
    } else {
      guidance = 'This comment is informational — editing it does not change what gets uploaded. Comment-only mode did not commit this generated changelog change to the PR branch, and same-repository PRs are not regenerated by the merge-time S3 upload. Add the generated entry to the PR branch before merging if it should be published.';
    }

    bodyParts.push(
      `Generated changelog entry for \`${escapeMarkdown(changelogDir + '/' + files[0])}\`:`,
      '',
      '```yaml',
      content,
      '```',
      '',
      guidance,
    );
  } else {
    bodyParts.push('⚠️ Changelog entry was generated but the file content could not be read.');
  }

  await upsertComment({ github, context, prNumber, body: bodyParts.join('\n') });
};
